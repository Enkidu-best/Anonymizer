"""General categories never masked (task 2, §2.1) — and real names still masked."""
import pytest

from core.lexicon import not_pii


@pytest.mark.parametrize('value', [
    'Арендатор', 'Арендатору', 'Стороной', 'Сторонами', 'Арендодателя', 'Генеральный директор',
    'генерального директора', 'Председатель Совета директоров', 'Главный бухгалтер', 'Поручитель',
    'Витрина', 'Арендодателя Арендная', 'ЦЕНА И ПОРЯДОК РАСЧЕТОВ', 'Залогодержателю',
])
def test_not_a_person(value):
    assert not_pii(value, 'ФИО')


@pytest.mark.parametrize('value', [
    'Центрального банка России', 'Банк России', 'БТИ', 'Росреестр', 'Минфина', 'ИФНС',
    'Арбитражный суд города Москвы', 'Управление Федеральной службы', 'Заказчик', 'Общество',
])
def test_not_a_company(value):
    assert not_pii(value, 'ЮЛ')


@pytest.mark.parametrize('value,etype', [
    ('Иванов Пётр Сергеевич', 'ФИО'), ('ИВАНОВ ИВАН ИВАНОВИЧ', 'ФИО'), ('Кацнельс Б.', 'ФИО'),
    ('Белозёрову Аркадию', 'ФИО'), ('СЕВЕРНЫЙ ТОРГОВЫЙ БАНК', 'ЮЛ'), ('Вектор-Плюс', 'ЮЛ'),
    ('Уральская Логистика', 'ЮЛ'), ('Сигма Трейд', 'ЮЛ'), ('Пастухов', 'ФИО'), ('Кузнецов', 'ФИО'),
])
def test_real_names_kept(value, etype):
    assert not not_pii(value, etype)
